# -*- coding: utf-8 -*-
"""官网与 miniapp 的契约自检（三项）。

官网和教师端/后台是两个独立仓库、独立发布。只有三处需要一致，
这个脚本用来确认这三处没有悄悄走样：

  1. 颜色令牌：assets/design-colors.css 是 miniapp 真源的生成副本，
     两边共有的变量值必须一致。
  2. 入口地址：teacher/ 与 admin/ 两个中转页里的 href 和 JS TARGET 必须相同，
     且指向同一台 CloudBase 主机。
  3. 生成物标记：design-colors.css 头部必须保留 Generated by 标记，
     说明它没被手改过（手改会在下次同步时丢失）。

用法（在仓库根目录）：
    python tools/check_contract.py             # 联网拉真源后全查
    python tools/check_contract.py --offline   # 用上次缓存的真源比对

退出码 0 = 全部通过，1 = 有问题，2 = 无法检查。
"""
import base64
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)
CACHE = os.path.join(tempfile.gettempdir(), 'changtu-design-tokens.cache.css')
SITE_CSS = os.path.join(SITE, 'assets', 'design-colors.css')
TOKENS_PATH = 'design/changtu-design-tokens.css'
REPO = 'zhonghart62git/changtu-compass-miniapp'
ENTRY_PAGES = ['teacher/index.html', 'admin/index.html']

problems = []
notes = []


def github_token():
    try:
        out = subprocess.run(['git', 'credential', 'fill'],
                             input='protocol=https\nhost=github.com\n\n',
                             capture_output=True, text=True, timeout=20).stdout
        for line in out.splitlines():
            if line.startswith('password='):
                return line.split('=', 1)[1].strip()
    except Exception:
        pass
    return None


def fetch_tokens():
    tok = github_token()
    if not tok:
        return None, '没有可用的 GitHub 凭据'
    url = 'https://api.github.com/repos/%s/contents/%s' % (REPO, TOKENS_PATH)
    req = urllib.request.Request(url, headers={
        'Authorization': 'Bearer ' + tok,
        'Accept': 'application/vnd.github+json',
        'User-Agent': 'changtu-contract-check',
    })
    try:
        with urllib.request.urlopen(req, timeout=25) as r:
            data = json.load(r)
        text = base64.b64decode(data['content']).decode('utf-8', 'replace')
    except Exception as e:
        return None, str(e)
    with open(CACHE, 'w', encoding='utf-8', newline='') as f:
        f.write(text)
    return text, None


def vars_of(text):
    return {k.lower(): v.strip().lower()
            for k, v in re.findall(r'(--[a-zA-Z0-9-]+)\s*:\s*([^;{}]+);', text)}


def check_colors(offline):
    print('[1/3] 颜色令牌')
    if offline:
        if not os.path.exists(CACHE):
            print('      跳过：没有缓存副本，先不带 --offline 跑一次')
            notes.append('颜色检查跳过（无缓存）')
            return
        upstream, src = open(CACHE, encoding='utf-8').read(), '本地缓存'
    else:
        upstream, err = fetch_tokens()
        if upstream is None:
            print('      跳过：拉取真源失败（%s）' % err)
            notes.append('颜色检查跳过（拉取失败）')
            return
        src = 'miniapp 远端'

    if not os.path.exists(SITE_CSS):
        problems.append('找不到 assets/design-colors.css')
        return

    a = vars_of(upstream)
    b = vars_of(open(SITE_CSS, encoding='utf-8').read())
    shared = [k for k in a if k in b]
    drift = [(k, a[k], b[k]) for k in shared if a[k] != b[k]]

    if drift:
        print('      漂移 %d 项：' % len(drift))
        for k, x, y in drift:
            print('        %-24s miniapp=%-14s 官网=%s' % (k, x, y))
        problems.append('颜色令牌漂移 %d 项，需在 miniapp 侧重新同步' % len(drift))
    else:
        print('      通过：%d 个共有变量值一致（真源：%s）' % (len(shared), src))


def check_entries():
    print('[2/3] 入口地址')
    hosts = set()
    for rel in ENTRY_PAGES:
        p = os.path.join(SITE, rel)
        if not os.path.exists(p):
            problems.append('%s 不存在' % rel)
            continue
        s = open(p, encoding='utf-8').read()
        hrefs = re.findall(r'href="(https://[^"]*tcloudbase\.com[^"]*)"', s)
        targets = re.findall(r"var\s+TARGET\s*=\s*'([^']+)'", s)
        allurls = set(hrefs) | set(targets)
        if len(allurls) != 1:
            print('      %-22s 地址不一致：%s' % (rel, sorted(allurls)))
            problems.append('%s 里的跳转地址不一致（%d 种）' % (rel, len(allurls)))
            continue
        url = allurls.pop()
        host = re.match(r'https://([^/]+)', url).group(1)
        hosts.add(host)
        print('      %-22s %s' % (rel, url))

    if len(hosts) > 1:
        problems.append('两个中转页指向不同主机：%s' % sorted(hosts))
    elif hosts:
        print('      通过：两个入口同主机 %s' % hosts.pop())


def check_generated():
    print('[3/3] 生成物标记')
    if not os.path.exists(SITE_CSS):
        problems.append('找不到 assets/design-colors.css')
        return
    head = open(SITE_CSS, encoding='utf-8').read(400)
    if 'Generated by' in head and 'sync-design-colors' in head:
        print('      通过：design-colors.css 仍是生成文件')
    else:
        print('      警告：文件头缺少 Generated by 标记')
        problems.append('design-colors.css 的生成标记丢了，可能被手改过')


def main():
    offline = '--offline' in sys.argv
    check_colors(offline)
    check_entries()
    check_generated()

    print()
    if problems:
        print('发现 %d 个问题：' % len(problems))
        for p in problems:
            print('  - ' + p)
        return 1
    print('契约检查全部通过。')
    for n in notes:
        print('提示：' + n)
    return 0


if __name__ == '__main__':
    sys.exit(main())
